// Extracts Japanese stroke data for the curriculum from animCJK's graphicsJa.txt
// and graphicsJaKana.txt (https://github.com/parsimonhi/animCJK, Arphic Public
// License) into a lazily loaded module, so writing practice works offline and
// on iPhone.
//
// usage: node scripts/build-strokes.mjs path/to/graphicsJa.txt path/to/graphicsJaKana.txt
import { readFileSync, writeFileSync } from "node:fs";
import { kanjiData } from "../src/data/kanji.js";
import { radicalsData } from "../src/data/radicals.js";
import { ALL_KANA } from "../src/rush/kana.js";

const sources = process.argv.slice(2);
if (!sources.length) {
  console.error("usage: node scripts/build-strokes.mjs graphicsJa.txt graphicsJaKana.txt");
  process.exit(1);
}
const wanted = new Set([
  ...kanjiData.map((item) => item.kanji),
  ...radicalsData.map((item) => item.kanji),
  // Single kana only; contracted sounds (きゃ) are written as two characters.
  ...ALL_KANA.flatMap((kana) => [...kana]),
]);
const found = {};
for (const source of sources)
  for (const line of readFileSync(source, "utf8").split("\n")) {
    if (!line.trim()) continue;
    const { character, strokes, medians } = JSON.parse(line);
    if (!wanted.has(character)) continue;
    // Whole-unit medians are plenty for stroke matching and shrink the file.
    found[character] = {
      strokes,
      medians: medians.map((median) => median.map(([x, y]) => [Math.round(x), Math.round(y)])),
    };
  }
const missing = [...wanted].filter((character) => !found[character]);
const body =
  "// Generated by scripts/build-strokes.mjs from animCJK graphicsJa.txt and graphicsJaKana.txt.\n" +
  "// Stroke data © animCJK / Make Me a Hanzi, Arphic Public License: see strokes.LICENSE.txt.\n" +
  `export const strokeData = ${JSON.stringify(found)};\n`;
writeFileSync(new URL("../src/data/strokes.js", import.meta.url), body);
console.log(
  `wrote ${Object.keys(found).length} characters (${(body.length / 1024).toFixed(0)} KB); ` +
    `missing ${missing.length}: ${missing.join(" ")}`,
);
